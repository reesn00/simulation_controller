"""落盘与投影字段的**长度 / 条数上限**——**唯一真源**（H-41）。

为什么是单独一个模块
-------------------
这些数字原先散在四个文件里，各写各的：

- ``executor/orchestrator.py`` —— P1 落盘：元素名 **120** 字、链接文字 **80** 字；
- ``perception/llm_perceptor.py`` —— 送给模型：元素名 **60** 字、链接文字 **60** 字；
- ``executor/review_queue.py`` —— 复核页：元素名 **60** 字。

**同一个字段、三处三个值** ⇒ 后果不是「文件变大」，而是
「**模型看到的名字 ≠ 存档里的名字**」。

元素名是 rationale 引用的**主要锚点**：模型引用了一个存档里查不到的
字符串 ⇒ 训练出来的 rationale 指向一个**不存在的目标**。而这**不报任何错**
——两份数据各自都合法，只是说的不是同一件事（症状是「模型总在引用不存在
的元素」，排查时却找不到任何一处不一致，因为压根没有「一致」这个概念）。

⇒ 一律从这里取，且**四处同值**（P1 落盘 / 感知层 / 复核页 / 元素投影）。

条数上限同理（**四层必须同值**）
--------------------------------
交互元素 / 链接的条数上限散在**采集层**（浏览器驱动）、**落盘层**
（P1 存档）、**投影层**（送模型的那一份）三处。这三处**必须同值**，否则
D-2 评分器那条判据就废了：它靠「**落盘了几条**」与「**采到了几条**」的差
判断「目标是不是可能被裁掉了」——差只在**两处对齐**时才有意义
（见 :data:`trajectory_pipeline.executor.orchestrator.OBS_ELEMENT_LIMIT`
的注释）。

⚠️ **上限只管「字段」与「条数」，不管「内容」**：正文**字里行间**的裁剪
不在这里——那是 :mod:`trajectory_pipeline.assembler.observation_view` 与
:mod:`trajectory_pipeline.refine.refiner` 的职责（方案 26 §5 / §6）。
"""

#: 元素名（可访问名 / 可见文字）的长度上限。
#:
#: ⚠️ **取值 120 的理由**：元素名**本来就短**（按钮文字、链接文字、
#: ARIA 标签）——这个上限是**兜底**，不是「省字的旋钮」。
#: 取消 P2 的元素数量裁剪之后（方案 26 §6），它就是事实上的天花板，
#: 所以宁可留一个明确的数，也不要留一个「看情况」。
ELEMENT_NAME_LIMIT = 120

#: 链接**显示文字**的长度上限。
#:
#: ⚠️ 与 :data:`ELEMENT_NAME_LIMIT` 同款理由：链接文字本来就短。
#: URL 在 ``href`` 里**不裁**——那是可导航性的锚，裁了就点不到。
LINK_TEXT_LIMIT = 80

#: **正文**的字符预算——采集层、落盘层、送模型那一层**同值**（H-41 阶段 1）。
#:
#: ⚠️ **为什么它是「语料链的上游闸门」**：P1 存档 → P2 → P3/T 的正文都
#: 源于此 ⇒ 这里的截断**不可逆**（下游任何 LLM 都救不回来）⇒ 它是全链
#: 最该抬的一处，也是 owner「禁止做内容截断」这条指令的**真正落点**。
#:
#: ⚠️ **为什么是 200000**：owner 授权「LLM 输入 200k / 输出 128k」⇒
#: 采集层**不再有理由**自己设一个小预算。实测真实正文只有 ~3000 字
#: （本仓库真实 P1：3301 / 3253 / 2987 字）⇒ **抬预算在实际数据上几乎
#: 不涨体积**；而 6000 之所以曾经绑死，是因为**快照路径的 CSS 抢预算**
#: ——正文主来源 ``innerText`` **压根不带 CSS** ⇒ 抬预算对正文零副作用。
BODY_BUDGET_CHARS = 200_000

#: 交互元素的**条数**上限——采集 / 落盘 / 送模型**三层同值**（H-41）。
#:
#: ⚠️ **为什么必须三层同值**：D-2 评分器靠「落盘条数」与「采集条数」的
#: 差判断「目标是不是可能被裁掉了」⇒ 差只在对齐时才有意义 ⇒ 三层不等
#: 时它会**静默地把裁剪当成不存在**。
#:
#: ⚠️ **与跨面测量口径**（``element_basis.SHARED_LIMIT`` = 500）**故意
#: 不同**：那个数的是「**这个页面有多少**」，不是「我们留了多少」，
#: 超了会在账目里记 ``truncated``，不装作没有。
ELEMENT_COUNT_LIMIT = 200

#: 链接的**条数**上限——采集 / 落盘 / 送模型**三层同值**（H-41）。
#:
#: ⚠️ 与 :data:`ELEMENT_COUNT_LIMIT` 同值同理由：搜索页的链接总量常到
#: 100+，前 50 条几乎全是站内导航 / 相关搜索 / 热搜，**搜索结果条目排在其
#: 后**——按 50 条落盘等于把结果区整段截掉（owner 报的「轨迹里没有搜索的
#: 页面信息记录」）。
LINK_COUNT_LIMIT = 200

