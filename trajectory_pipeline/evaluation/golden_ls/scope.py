"""golden_ls.scope: **标注单元的粒度**（方案 23 · owner 裁定 ④）的唯一真源。

两种粒度
--------

============  ==========================================================
``site``      一行 = 一个**站点**（一次访问）。v1–v16 的历史口径。
``trajectory`` 一行 = 一条**轨迹**（一个 Run）。per-Run 之后的口径。
============  ==========================================================

⚠️ **为什么单独一个模块**：粒度这个词同时出现在三处——
``projects``（台账按 ``(版本, 粒度)`` 找项目）、``label_config``
（渲染时页眉写「站点」还是「轨迹」）、``cli``（``--scope``）。
三处各写一份字面量，迟早有一处写成 ``traj`` 而另一处仍认 ``trajectory``
⇒ **粒度认不出来**（要么报错，要么静默回落成另一个粒度）⇒
**两种粒度的行混进同一个项目**，而标注员分不清自己在判一条轨迹还是判一个站点。

⇒ 两个字面量只在这里写一次，别处一律 import。
"""

from __future__ import annotations

__all__ = ["SCOPES", "SCOPE_SITE", "SCOPE_TRAJECTORY"]


#: 站点级（历史口径）：一条站点行 = 一个 LS 任务。
SCOPE_SITE = "site"

#: 轨迹级（现行口径 · 裁定 ④）：一条轨迹 = 一个 LS 任务 = 一个标注单元。
SCOPE_TRAJECTORY = "trajectory"

#: 全部粒度（顺序即报表顺序）。
SCOPES: tuple[str, ...] = (SCOPE_SITE, SCOPE_TRAJECTORY)
