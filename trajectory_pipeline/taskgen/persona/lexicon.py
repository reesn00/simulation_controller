"""各 persona 维度的语言特征表——**纯数据 + 纯确定性查表**。

三张表，职责不同：

1. :data:`DIMENSION_FEATURES` —— 维度 → 可观察语言现象。**给人看**，
   兼作覆盖度自检（画像库缺哪一档会立刻显示出来）。
2. :data:`OPENERS` / :data:`GENRE_TERMS` / :data:`SPECIFICITY_RENDER` —— 模板片段。
   :mod:`renderer` 只做查表 + 槽位填充，**不做自由生成**。
3. :data:`CONSTRAINT_PROBES` —— 判分保真的**可执行检查**。

为什么第 3 张表是关键
--------------------
铁律是「persona 与改写**只改表述不改判分**」。但这条纪律如果只写成注释，
就没有任何东西能验证它——改写把「注明可观看的集数范围」悄悄删了，
没有任何报错，样本站得住、任务还是那个任务，只是**要求消失了**。
这类丢失不报错，所以必须做成**代码可执行的探针**：
把「这条表述还保不保留该条判分要求」变成一次确定性的字符串检查，
由 :mod:`trajectory_pipeline.taskgen.normalizer` 在改写后立即执行。

不通过不报错、不重试、不修正——直接丢弃改写、退回骨架原文。
理由与 :mod:`executor.dom` 一致：**猜出来的「修好了」比明摆着的「坏了」贵**，
因为前者会混进训练集且带着通过的假象。
"""

