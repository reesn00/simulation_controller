#: ``task_specificity`` 各档在**有片名**时的措辞。
#:
#: ⚠️ **W1 只渲染得出「指名」一档**，另外两档在
#: :mod:`trajectory_pipeline.taskgen.persona.renderer` 里被降级/排除。
#: 原因不是词表没写够，而是**查表渲染器读不懂任务内容**：
#:
#: 「半指代」的本质是「说得出品类线索、说不出片名」——
#: 比如任务是找某纪录片时，应该说「去年那部讲南极的」而不是片名。
#: 这条线索必须**来自骨架**，而不是来自 persona（persona 只知道用户喜欢什么品类，
#: 不知道这个任务在找什么）。所以早期版本写成
#: ``"跟《{title}》差不多的那种"``——它把片名又塞回了参照物里，
#: 产出的其实是**半指名**而不是半指代，自欺欺人。
#:
#: 要真做半指代，需要读懂骨架内容再决定说哪条线索，
#: 那是 W3 LLM 改写器的活。现在老实降级，并把原因落进 provenance，
#: 好让切片表区分「这一档没做」与「这一档做了但没生效」。
