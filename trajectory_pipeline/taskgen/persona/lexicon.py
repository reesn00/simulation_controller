#: ⚠️ **这里曾有两张表，已删**（2026-11-11）：``CLOSERS``（urgency 的
#: 催促句）与 ``VERBAL_TAILS``（verbal_style 的句尾语气词）。
#:
#: 删除理由：**时间限定与语气词对 agent prompt 没有意义**。
#: 「今天就要看到」「这周内给我就行」「…就行啊。」改的是**用户的心情**，
#: 不是**用户要什么**——而 persona 的唯一产出物就是首轮表述，
#: 它喂给 agent 之后，agent 要解的正是「用户要什么」；
#: 这些修饰成分既不携带约束，也不改变检索目标，只在读起来更像真人。
#:
#: 更要紧的是**它们是假切片轴**：这两维一旦留在画像上，
#: 切片表就会报「立即 × 长尾」与「闲时 × 长尾」的表现差异，
#: 而两组的首轮表述**除了这几个修饰词之外完全相同**——
#: 差异是纯噪声，却长得像"发现了一个显著问题"。
#: 一个维度若在渲染里落不了地，就必须从画像上删掉，
